-- find top 3 purchased courses
select c.course_id,c.course_name,(sum(p.quantity)) as total_quantity from courses as c
inner join purchases as p
on c.course_id = p.course_id
group by c.course_id,c.course_name
order by total_quantity desc limit 3;

-- category wise revenue and unique learner count
select c.category , round(sum(c.unit_price*p.quantity),2) as total_revenue,
count(distinct(p.learner_id)) as unique_leaners 
from courses as c
inner join purchases as p
on c.course_id = p.course_id
group by c.category
order by total_revenue desc;

-- list all learner who has purchase more than one category
select p.learner_id, count(distinct(c.category)) as total_categories from purchases as p
inner join courses as c
on p.course_id = c.course_id
group by p.learner_id
having count(distinct c.category)>1
order by total_categories desc;

-- identify the courses have not been purchased at all
select c.course_id,c.course_name from courses as c
 left join purchases as p 
 on c.course_id= p.course_id
 where p.course_id is null;


