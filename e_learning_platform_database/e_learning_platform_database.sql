 -- total revenue generated by each course
 select c.course_name,sum(p.quantity*c.unit_price)as total_revenue 
 from courses as c
 inner join purchases as p
 on c.course_id = p.course_id
 group by c.course_name
 order by total_revenue desc;

-- total spending by each learner
select l.full_name as learner_name ,l.country,sum(p.quantity*c.unit_price) as total_spend
from learners as l
inner join purchases as p
on l.learner_id = p.learner_id
inner join courses as c
on c.course_id= p.course_id
group by l.learner_id,l.country
order by total_spend desc; 

-- country wise revenue
select l.country, sum(p.quantity*c.unit_price) as total_revenue
from learners as l
inner join purchases as p
on l.learner_id = p.learner_id
inner join courses as c
on c.course_id = p.course_id
group by l.country
order by total_revenue asc;

-- total no of learners by country
select country , count(learner_id) as total_learners from learners
group by country
order by total_learners desc;

-- avg purchase  value
select round(avg(p.quantity*c.unit_price),2) as avg_purchase_value
from purchases as p
left join courses c
on p.course_id = c.course_id;

-- monthly revenue trend
select date_format(p.purchase_date,'%m')as purchase_month, round(sum(p.quantity*c.unit_price)) as total_revenue
from purchases as p
left join courses as c
on p.course_id = c.course_id
group by date_format(p.purchase_date,'%m')
order by purchase_month;

 select p.purchase_id,p.quantity,c.unit_price,round(quantity*c.unit_price) as total_amount
 from purchases as p
